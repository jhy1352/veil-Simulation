  canonicalMutation: 'YES' | 'NO';
  contextPreserved: 'YES' | 'NO' | 'UNPROVEN';
  llm2Called: 'CALLED' | 'NOT CALLED';
  recoveryNarrative: 'SUCCESS' | 'FAIL' | 'UNPROVEN';
  rawJsonLeak: 'YES' | 'NO';
  finalVerdict: ForensicVerdict;

  // Forensic evidence details
  turnNumber: number;
  promptSent: string;
  rawLlm1Response: string;
  parsedCandidates: any[];
  recoveryGateResult: any;
  preAuthResults: any[];
  llm2PromptSent?: string;
  rawLlm2Response?: string;
