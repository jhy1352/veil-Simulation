export interface CaseExecutionResult {
  caseId: string;
  scenarioName: string;
  playerInput: string;
  verdict: 'REPRODUCED' | 'NOT REPRODUCED' | 'DIFFERENT FAILURE';
  failureStage: string;
  cause: string;
  evidenceSummary: string;
  turnCount: number;
  promptSent: string;
  rawLlmResponse: string;
  candidatesParsed: any[];
  recoveryGateResult: any;
  preAuthResult: any;
  selectedCandidateId: number | null;
  commitResult: any;
  stateBefore: any;
  stateAfter: any;
  stateDiff: any;
  historyRecordsCreated: ImmutableHistoricalRecord[];
  traceLog: string[];
}

// Compute deep diff between two objects
function getObjectDiff(before: any, after: any): any {
  const diff: any = {};
  for (const key of Object.keys(after)) {
    if (JSON.stringify(before[key]) !== JSON.stringify(after[key])) {
      diff[key] = {
        before: before[key],
        after: after[key]
      };
    }
  }
  return diff;
}

// Pipeline executor for a single turn/scenario
async function executeRuntimeTurn(
  caseId: string,
  scenarioName: string,
  playerInput: string,
  engine: SovereignEngine,
  turnNumber: number,
  conversationHistory: { role: 'user' | 'model'; text: string }[]
): Promise<CaseExecutionResult> {
  const traceLog: string[] = [];
  traceLog.push(`=== START SCENARIO ${caseId}: ${scenarioName} ===`);
  traceLog.push(`[STAGE 1: PLAYER INPUT] "${playerInput}" (Turn ${turnNumber})`);

  const snapshotBefore = engine.getSnapshot();
  const stateBeforeJson = JSON.parse(JSON.stringify(snapshotBefore));

  // Build Context Prompt
  const activeSeedsContext = (snapshotBefore.worldInfo.seeds || [])
    .filter((s: any) => s.status === 'active' || s.status === 'dormant')
    .map((s: any) => `- [Seed ID: ${s.id}] ${s.content}`)
    .join('\n');

  const contextPrompt = `[TRPG Campaign Context]
- 세계관명: ${snapshotBefore.worldInfo.worldName}
- 세계관 설정: ${snapshotBefore.worldInfo.settingDescription}
- 문체 스타일: ${snapshotBefore.worldInfo.toneStyle}
- 주인공 프로필: ${snapshotBefore.character.name} (나이: ${snapshotBefore.character.age}, 성별: ${snapshotBefore.character.gender})
  * 출신/배경: ${snapshotBefore.character.originBackground}
  * 목적: ${snapshotBefore.character.goal}
  * 능력치: STR ${snapshotBefore.character.stats?.strength} / AGI ${snapshotBefore.character.stats?.agility} / CON ${snapshotBefore.character.stats?.constitution} / INT ${snapshotBefore.character.stats?.intelligence} / WIS ${snapshotBefore.character.stats?.wisdom} / CHA ${snapshotBefore.character.stats?.charisma}
  * 소장품: ${snapshotBefore.character.inventory.map((i: any) => `${i.name}(x${i.quantity})`).join(', ') || '없음'}
[ACTIVE SEEDS]
${activeSeedsContext || '없음'}`;

  // Assemble Gemini contents
  const contents: any[] = [];
  if (conversationHistory.length === 0) {
    contents.push({
      role: 'user',
      parts: [{ text: `${contextPrompt}\n\n[TURN ${turnNumber} PLAYER PROMPT]\n${playerInput}` }]
    });
  } else {
    conversationHistory.forEach((msg, idx) => {
      let t = msg.text;
      if (idx === 0 && msg.role === 'user') {
        t = `${contextPrompt}\n\n[HISTORICAL DIALOGUE]\n${t}`;
      }
      contents.push({
        role: msg.role,
        parts: [{ text: t }]
      });
    });
    contents.push({
      role: 'user',
      parts: [{ text: playerInput }]
    });
  }

  const fullPromptStr = JSON.stringify(contents, null, 2);
  traceLog.push(`[STAGE 2: LLM PROMPT GENERATED] Prompt Size: ${fullPromptStr.length} chars`);

  // Call Gemini API (Strict 1 API call per Turn - Constitution Article 64)
  let rawLlmResponse = '';
  let modelName = 'gemini-3.7-flash';

  traceLog.push(`[STAGE 3: CALLING LLM API] Model: ${modelName}`);
  console.log(`[FORENSIC RUNNER] Case ${caseId} (Turn ${turnNumber}) -> Calling Gemini API...`);

  try {
    const res = await ai.models.generateContent({
      model: modelName,
      contents,
      config: {
        systemInstruction: MASTER_SYSTEM_INSTRUCTION
      }
    });
    rawLlmResponse = res.text || '';
    traceLog.push(`[STAGE 3: LLM RESPONSE RECEIVED] Length: ${rawLlmResponse.length} chars`);
    console.log(`[FORENSIC RUNNER] Case ${caseId} (Turn ${turnNumber}) -> Response received (${rawLlmResponse.length} chars)`);
  } catch (err: any) {
    traceLog.push(`[STAGE 3: LLM CALL FAILED] Error: ${err.message}`);
    return {
      caseId,
      scenarioName,
      playerInput,
      verdict: 'DIFFERENT FAILURE',
      failureStage: 'LLM_API_CALL',
      cause: err.message,
      evidenceSummary: `LLM API call failed with error: ${err.message}`,
      turnCount: turnNumber,
      promptSent: fullPromptStr,
      rawLlmResponse: '',
      candidatesParsed: [],
      recoveryGateResult: null,
      preAuthResult: null,
      selectedCandidateId: null,
      commitResult: null,
      stateBefore: stateBeforeJson,
      stateAfter: stateBeforeJson,
      stateDiff: {},
      historyRecordsCreated: [],
      traceLog
    };
  }

  // Parse Candidate Block
  const rawCandidates = parseCandidatesBlock(rawLlmResponse);
  traceLog.push(`[STAGE 4: PARSE CANDIDATE BLOCK] Raw candidates extracted: ${rawCandidates ? rawCandidates.length : 'NULL'}`);

  if (!rawCandidates || rawCandidates.length === 0) {
    traceLog.push(`[STAGE 4] No CANDIDATES_BLOCK found or empty candidates array -> Non-mutation turn (LLM OMITTED)`);
    const { cleanText } = parseGMResponseMetaData(rawLlmResponse);
    conversationHistory.push({ role: 'user', text: playerInput });
    conversationHistory.push({ role: 'model', text: cleanText || rawLlmResponse });
    return {
      caseId,
      scenarioName,
      playerInput,
      verdict: 'NOT REPRODUCED',
      failureStage: 'NONE (NON_MUTATION_PROSE)',
      cause: 'LLM generated pure literary prose without state mutation proposals (LLM Omitted)',
      evidenceSummary: 'parseCandidatesBlock returned null or empty array; non-mutation narrative processed safely without unbacked state changes',
      turnCount: turnNumber,
      promptSent: fullPromptStr,
      rawLlmResponse,
      candidatesParsed: [],
      recoveryGateResult: null,
      preAuthResult: null,
      selectedCandidateId: null,
      commitResult: { success: true, reason: 'NON_MUTATION_PROSE' },
      stateBefore: stateBeforeJson,
      stateAfter: stateBeforeJson,
      stateDiff: {},
      historyRecordsCreated: [],
      traceLog
    };
  }

  // Candidate Recovery Gate
  const recoveryGateResult = runCandidateRecoveryGate<VeilCandidate>(rawCandidates);
  traceLog.push(`[STAGE 5: CANDIDATE RECOVERY GATE] Passed: ${recoveryGateResult.passedCandidates.length}, Quarantined: ${recoveryGateResult.quarantinedCount}`);

  if (recoveryGateResult.passedCandidates.length === 0) {
    traceLog.push(`[STAGE 5 FAILURE] All candidates quarantined by CandidateRecoveryGate`);
    return {
      caseId,
      scenarioName,
      playerInput,
      verdict: 'DIFFERENT FAILURE',
      failureStage: 'CANDIDATE_RECOVERY_GATE',
      cause: `All ${rawCandidates.length} candidates were quarantined due to schema/field violations`,
      evidenceSummary: `quarantinedCandidates: ${JSON.stringify(recoveryGateResult.quarantinedCandidates)}`,
      turnCount: turnNumber,
      promptSent: fullPromptStr,
      rawLlmResponse,
      candidatesParsed: rawCandidates,
      recoveryGateResult,
      preAuthResult: null,
      selectedCandidateId: null,
      commitResult: null,
      stateBefore: stateBeforeJson,
      stateAfter: stateBeforeJson,
      stateDiff: {},
      historyRecordsCreated: [],
      traceLog
    };
  }

  // Build CanonicalState for pre-auth
  const canonicalState: CanonicalState = {
    stateVersion: snapshotBefore.stateVersion,
    turn: turnNumber,
    worldInfo: snapshotBefore.worldInfo,
    character: snapshotBefore.character,
    lastCommittedEventId: snapshotBefore.lastCommittedEventId,
    lastCommittedAt: snapshotBefore.lastCommittedAt
  };

  const executedRequestIds = new Set<string>();
  const recordedEventIds = new Set<string>();
  const historicalRecords = engine.getHistory();
  const playerInputId = generateProposalId('input');

  // Translation to Proposals
  const translatedCandidates = recoveryGateResult.passedCandidates.map(c => {
    const candidatePacket = extractCandidatesFromMetadata(
      c.rawMetadata || {},
      turnNumber,
      snapshotBefore.worldInfo.currentTime?.formattedTime || '1년차 봄 1일',
      c.candidateId
    );
    const proposal: StateTransitionProposal = buildSafeProposalFromCandidate(
      canonicalState,
      candidatePacket,
      turnNumber,
      historicalRecords,
      playerInputId
    );
    return {
      candidate: c,
      candidatePacket,
      proposal,
      meaningTree: proposal.meaningTree!
    };
  });

  traceLog.push(`[STAGE 6: PROPOSAL TRANSLATION] Translated ${translatedCandidates.length} candidates to StateTransitionProposals`);

  // Diversity Gate
  const diverseCandidatesWithTrees = filterDiverseCandidates(
    translatedCandidates.map(tc => ({ candidate: tc.candidatePacket, meaningTree: tc.meaningTree }))
  );
  const candidatesToValidate = translatedCandidates.filter(tc =>
    diverseCandidatesWithTrees.some(d => d.candidate === tc.candidatePacket)
  );

  traceLog.push(`[STAGE 7: DIVERSITY GATE] Retained ${candidatesToValidate.length} candidates after deduplication`);

  // Pre-Authorization Validation (Validator)
  const preAuthResults = candidatesToValidate.map(tc => {
    const validation = EngineValidator.validate(
      tc.proposal,
      canonicalState,
      executedRequestIds,
      recordedEventIds,
      historicalRecords
    );
    return {
      candidateId: tc.candidate.candidateId,
      candidate: tc.candidate,
      proposal: tc.proposal,
      candidatePacket: tc.candidatePacket,
      isValid: validation.isValid,
      rejectedReasons: validation.rejectedReasons,
      conflictDetails: validation.conflictDetails
    };
  });

  const allowedCandidates = preAuthResults.filter(r => r.isValid);
  traceLog.push(`[STAGE 8: ENGINE VALIDATOR PRE-AUTH] Allowed: ${allowedCandidates.length}, Rejected: ${preAuthResults.length - allowedCandidates.length}`);

  preAuthResults.forEach(r => {
    traceLog.push(`  - Candidate ${r.candidateId}: isValid=${r.isValid}, reasons=[${r.rejectedReasons.concat(r.conflictDetails).join('; ')}], actions=${JSON.stringify(r.proposal.actions.map(a => a.type))}`);
  });

  if (allowedCandidates.length === 0) {
    traceLog.push(`[STAGE 8 REJECTION] ALL candidates rejected by Sovereign Engine Validator (ENGINE BLOCKED). Rejection reasons: ${preAuthResults.map(r => `Cand ${r.candidateId}: ${r.rejectedReasons.join(', ')}`).join(' | ')}`);
    
    const { cleanText } = parseGMResponseMetaData(rawLlmResponse);
    conversationHistory.push({ role: 'user', text: playerInput });
    conversationHistory.push({ role: 'model', text: cleanText || rawLlmResponse });

    return {
      caseId,
      scenarioName,
      playerInput,
      verdict: 'NOT REPRODUCED', // Engine successfully blocked unverified mutations (ENGINE BLOCKED)
      failureStage: 'NONE (ENGINE_BLOCKED)',
      cause: `Sovereign Engine successfully enforced Fail-Closed defense on invalid state proposal: ${preAuthResults.flatMap(r => r.rejectedReasons).join('; ')}`,
      evidenceSummary: `EngineValidator successfully blocked ${preAuthResults.length} invalid candidate(s). Fail-Closed non-mutation preserved.`,
      turnCount: turnNumber,
      promptSent: fullPromptStr,
      rawLlmResponse,
      candidatesParsed: rawCandidates,
      recoveryGateResult,
      preAuthResult: preAuthResults,
      selectedCandidateId: null,
      commitResult: { success: false, reason: 'PRE_AUTH_ALL_REJECTED (ENGINE_BLOCKED)' },
      stateBefore: stateBeforeJson,
      stateAfter: stateBeforeJson,
      stateDiff: {},
      historyRecordsCreated: [],
      traceLog
    };
  }

  // Candidate 1 selected
  const selectedObj = allowedCandidates[0];
  const selectedCandidateId = selectedObj.candidateId;
  const authorizedProposal = selectedObj.proposal;

  traceLog.push(`[STAGE 9: CANDIDATE SELECTION] Selected Candidate ${selectedCandidateId} for Sovereign Commit`);

  // Sovereign Engine Commit
  const historyBeforeCount = engine.getHistory().length;
  const commitResult = engine.submitProposal(authorizedProposal);
  const historyAfter = engine.getHistory();
  const newHistoryRecords = historyAfter.slice(historyBeforeCount);

  traceLog.push(`[STAGE 10: SOVEREIGN COMMIT] Commit Success: ${commitResult.success}`);

  if (!commitResult.success) {
    traceLog.push(`[STAGE 10 FAILURE] Sovereign Commit failed: ${commitResult.error}`);
    return {
      caseId,
      scenarioName,
      playerInput,
      verdict: 'DIFFERENT FAILURE',
      failureStage: 'SOVEREIGN_COMMIT',
      cause: commitResult.error || 'Commit failed during state transition',
      evidenceSummary: `submitProposal failed: ${commitResult.error}`,
      turnCount: turnNumber,
      promptSent: fullPromptStr,
      rawLlmResponse,
      candidatesParsed: rawCandidates,
      recoveryGateResult,
      preAuthResult: preAuthResults,
      selectedCandidateId,
      commitResult,
      stateBefore: stateBeforeJson,
      stateAfter: stateBeforeJson,
      stateDiff: {},
      historyRecordsCreated: [],
      traceLog
    };
  }

  const snapshotAfter = engine.getSnapshot();
  const stateAfterJson = JSON.parse(JSON.stringify(snapshotAfter));
  const stateDiff = getObjectDiff(stateBeforeJson, stateAfterJson);

  traceLog.push(`[STAGE 11: STATE COMMIT SUCCESS] New State Version: ${snapshotAfter.stateVersion}, History Records Created: ${newHistoryRecords.length}`);
  traceLog.push(`[STAGE 11 STATE DIFF] ${JSON.stringify(stateDiff)}`);

  // Update conversation history for next turn
  const { cleanText } = parseGMResponseMetaData(rawLlmResponse);
  conversationHistory.push({ role: 'user', text: playerInput });
  conversationHistory.push({ role: 'model', text: cleanText || rawLlmResponse });

  return {
    caseId,
    scenarioName,
    playerInput,
    verdict: 'NOT REPRODUCED', // Successfully processed through entire pipeline!
    failureStage: 'NONE (COMMITTED)',
    cause: 'None - Successfully validated and committed to CanonicalState and History',
    evidenceSummary: `Successfully committed ${authorizedProposal.actions.length} action(s). State version: ${snapshotAfter.stateVersion}`,
    turnCount: turnNumber,
    promptSent: fullPromptStr,
    rawLlmResponse,
    candidatesParsed: rawCandidates,
    recoveryGateResult,
    preAuthResult: preAuthResults,
    selectedCandidateId,
    commitResult: {
      success: true,
      newHistoricalRecordsCount: newHistoryRecords.length,
      snapshotVersion: snapshotAfter.stateVersion
    },
    stateBefore: stateBeforeJson,
    stateAfter: stateAfterJson,
    stateDiff,
    historyRecordsCreated: newHistoryRecords,
    traceLog
  };
}

