// Retry wrapper for Gemini API calls to gracefully handle rate-limiting / quota limits (429)
async function generateContentWithRetry(params: any, maxRetries = 10, initialDelay = 70000): Promise<any> {
  let attempt = 0;
  while (attempt < maxRetries) {
    try {
      return await ai.models.generateContent(params);
    } catch (error: any) {
      const errorStr = String(error);
      const isRateLimit = error?.status === 429 || 
                          errorStr.includes('429') || 
                          errorStr.includes('Quota exceeded') || 
                          errorStr.includes('RESOURCE_EXHAUSTED') ||
                          errorStr.includes('rateLimitExceeded');
      if (isRateLimit) {
        attempt++;
        const delay = initialDelay * Math.pow(1.5, attempt - 1);
        console.warn(`\n[Gemini API 429 Quota Exceeded] Sleeping ${delay / 1000}s before retry (Attempt ${attempt}/${maxRetries})...`);
        await new Promise(resolve => setTimeout(resolve, delay));
      } else {
        throw error;
      }
    }
  }
  throw new Error(`Max retries reached for generateContent due to Quota limits.`);
}

